def _native_name_order(language: Language) -> str:
    return "".join(
        char
        for char in normalize("NFKD", LANGUAGE_NAMES[language].casefold())
        if not combining(char)
    )


# Presentation order only: pinned choices, Latin native names, then Greek,
# Cyrillic, Armenian, Georgian, Japanese, Korean, Thai, Devanagari, Bengali, Tamil, Telugu,
# Sinhala, Ethiopic and Khmer script groups.
_PINNED: tuple[Language, ...] = ("zh", "zh-TW", "en")
_SCRIPT_GROUPS: tuple[tuple[Language, ...], ...] = (
    ("el",),
    ("bg", "ru", "uk", "kk", "mn", "tg", "ky"),
    ("hy",),
    ("ka",),
    ("ja",),
    ("ko",),
    ("th",),
    ("hi", "mr", "ne"),
    ("bn",),
    ("ta",),
    ("te",),
    ("si",),
    ("am", "ti"),
    ("km",),
)
LANGUAGE_DISPLAY_ORDER: tuple[Language, ...] = (
    *_PINNED,
    *sorted(
        (
            language
            for language in LANGUAGES
            if language not in _PINNED
            and not any(language in group for group in _SCRIPT_GROUPS)
        ),
        key=_native_name_order,
    ),
    *(
        language
        for group in _SCRIPT_GROUPS
        for language in sorted(group, key=_native_name_order)
    ),
)


